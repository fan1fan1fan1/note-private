""" 给定一个正整数N(100<=N<=999) 交换三位数中的任意两位得到一个新的数字
    使得这个数字最大 并输出 如果都不大 输出原来的N

    样例输入 145
    输出 541

    一共三位数 全排列 输出最大的即可
"""
n = int(input())
a = n//100 # 百位数
b = n//10%10 # 十位数
c = n%10 # 个位数

n1 = b*100+a*10+c
n2 = b*100+c*10+a
n3 = a*100+c*10+b
n4 = c*100+b*10+a
n5 = c*100+a*10+b

res = max(n,n1,n2,n3,n4,n5)
print(res)




